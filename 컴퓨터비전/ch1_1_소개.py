# Q7. 검출과 분할의 차이는?
# A. 검출은 대상 위치를 상자 등으로, 분할은 픽셀별 영역을 마스크 등으로 표현한다.
#
# Q8. 매 프레임 검출하면 곧 추적인가?
# A. 프레임 사이에서 같은 대상을 연결하는 과정이 필요하다. 검출 반복만으로 ID가 유지되지는 않는다.
#
# Q9. 추적과 행동 분석의 차이는?
# A. 추적은 같은 대상의 시간상 연결, 행동 분석은 무엇을 하는지의 해석이다.
#
# Q10. 생성 비전과 멀티모달의 차이는?
# A. 생성은 새 시각 정보를 만드는 목표, 멀티모달은 서로 다른 정보 형태를 함께 다루는 방식이다.
#
# Q11. 고전 비전의 특징·장단점은?
# A. 설계한 특징·규칙 중심이다. 단계 확인이 쉽지만 환경 변화에 따라 수동 조정이 늘 수 있다.
#
# Q12. 딥러닝 비전의 특징·장단점은?
# A. 데이터에서 표현을 학습한다. 복잡한 패턴에 유리할 수 있지만 자료·계산·분포 변화의 영향을 받는다.
#
# Q13. 최적화로 문제를 푼다는 뜻은?
# A. 목표를 비용·제약으로 쓰고 비용을 줄이는 해를 찾는다. 비용 설계와 탐색의 가정이 중요하다.
#
# Q14. 선형대수·미적분·통계가 쓰이는 예는?
# A. Harris 행렬·좌표 변환 / Sobel 미분·에너지 갱신 / 히스토그램·Otsu 분산·색 모델.
#
# Q15. 배열 [1,2,3]+[10,20,30]의 출력은?
# A. NumPy 배열이면 print 결과는 [11 22 33]. Python list이면 [1, 2, 3, 10, 20, 30].
#
# Q16. 시간 출력의 소수값을 외우지 않는 이유는?
# A. 입력·하드웨어·실행 상태에 따라 변하기 때문이다. 단위와 작업 범위·출력 결과를 비교한다.
#
# Q17. ImageNet과 ILSVRC는 같은 것인가?
# A. 전체 영상 데이터베이스와 그 일부 등을 이용한 평가 대회를 구분해야 한다.
#
# Q18. 학습·검증·테스트의 역할은?
# A. 매개변수 학습 / 설정 선택 / 최종 평가. 테스트로 조건을 반복 조정하면 독립 평가가 약해진다.
#
# Q19. 손 그림자가 남는 현상을 1장 개념으로 설명하면?
# A. 조명으로 피부색이 바뀌고 그림자와 색이 겹친다. 제한된 색 조건에는 누락·오검출의 절충이 있다.
#
# Q20. 현재 Harris 예제가 하는 일은?
# A. 관심점 응답 계산, 직접 구현에서는 NMS까지 한다. 기술자·매칭·추적 전체를 수행하지는 않는다.


