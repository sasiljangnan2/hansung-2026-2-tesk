#%% 1. 컴퓨터비전이란? [PPT 2~3쪽]
# 컴퓨터비전(computer vision)은 영상·동영상에서 물체와 장면의 의미 있는 정보를 추출하고 해석하는 분야이다.
# 컴퓨터가 직접 받는 입력은 밝기와 색을 나타내는 숫자 배열이지만, 원하는 답은 그 숫자 이상의 의미이다.
# 예를 들어 픽셀 값이 120이라는 사실과 그 픽셀이 손인지 배경인지를 아는 것은 서로 다르다.
# 출력은 물체의 종류·위치·모양·거리·자세·움직임·행동·물체 사이 관계 등이 될 수 있다.
# 영상으로 3차원 세계의 성질을 측정하거나, 로봇이 행동할 근거를 만드는 것도 포함한다.
# 사람의 시각 기능 일부를 기계로 수행하게 하는 것이 목표이며, 특정 과제에서는 사람보다 높은 성능도 가능하다.
# 다만 특정 과제의 높은 성능을 인간 시각 전체나 범용 지능의 재현과 같다고 보지는 않는다.
#
# [비교] 영상처리 / 컴퓨터비전 / 컴퓨터그래픽스
# 영상처리(image processing): 영상 → 변환된 영상. 잡음 제거·밝기 조절·색 공간 변환 등이 대표적이다.
# 컴퓨터비전: 영상 → 장면에 대한 정보·설명. 물체 검출·영역 분할·거리 추정 등이 대표적이다.
# 컴퓨터그래픽스(graphics): 장면·모델의 설명 → 영상. 3D 모델·재질·조명으로 화면을 렌더링한다.
# 위 구분은 전형적인 목표이다. 분할처럼 비전 결과가 영상 모양의 마스크로 나타날 수도 있다.
# 실제 시스템에서는 영상처리로 입력을 정리하고, 비전으로 해석한 뒤, 그래픽스로 결과를 표시할 수 있다.
#
# [기존 코드 연결]
# ch2_2_픽셀.py: type·shape·픽셀 값으로 영상이 어떤 배열인지 확인한다. 물체 의미를 인식하는 단계는 아니다.
# ch3_1_HSV.py: BGR→HSV처럼 영상의 표현을 바꾸는 영상처리이다.
# ch3_2_풍선.py: 정한 파란색 범위의 픽셀을 선택하는 분할이다. 범용 학습 물체 검출기는 아니다.
#
# [한 문장 답안]
# 컴퓨터비전은 영상의 숫자 배열에서 물체와 장면의 의미 있는 정보를 추출·해석하고 세계의 성질을 추정하는 분야이다.


#%% 2. 비전은 왜 역문제인가? [PPT 3쪽]
# 정방향 과정: 실제 물체·재질·조명·카메라가 주어졌을 때 어떤 영상이 생기는지 생각하는 방향이다.
# 역문제(inverse problem): 관측된 영상에서 그 영상을 만든 원래 물체·깊이·조명 등의 원인을 추정한다.
# 비전의 중요한 과제는 2차원 관측으로 3차원 세계를 이해하는 것이므로 역문제로 설명한다.
#
# 어려운 이유는 영상을 만드는 과정에서 정보가 줄어들기 때문이다.
# 작고 가까운 물체와 크고 먼 물체가 영상에서는 비슷한 크기로 찍힐 수 있다.
# 어두운 재질과 밝은 재질 위의 그림자가 비슷한 밝기 값으로 보일 수도 있다.
# 즉 서로 다른 실제 원인이 같은 관측과 맞을 수 있어, 한 장의 영상만으로 답을 유일하게 정하기 어렵다.
#
# Ill-posed problem: 해의 존재·유일성·입력 변화에 대한 안정성 중 일부가 보장되지 않는 문제이다.
# 이 세 조건은 개념을 이해하기 위한 보충 설명이다. PPT는 특히 '여러 해석이 가능하다'는 점을 강조한다.
# 가정·사전 지식·여러 시점·시간 정보·학습 자료 등을 더하면 가능한 해석을 줄일 수 있다.
# 정보를 더했다고 모든 상황에서 정답이나 유일한 해가 보장되는 것은 아니다.
#
# [한 문장 답안]
# 비전은 투영으로 정보가 줄어든 2D 영상에서 원래 세계를 추정하므로 여러 원인이 같은 관측을 설명하는 역문제이다.


#%% 3. 컴퓨터비전은 왜 어려운가? [PPT 10쪽]
# (1) 환경 변화: 낮/밤·날씨·조명·그림자로 같은 물체의 밝기·색·대비가 바뀐다.
# (2) 시점 변화: 보는 위치·방향·거리 때문에 회전·크기·원근·보이는 면이 달라진다.
# (3) 모양 변화: 강체는 형태를 유지하며 자세가 바뀌고, 손·옷 같은 연성 물체는 내부 상대 모양도 바뀐다.
# (4) 가림·배경: 물체 일부가 안 보이거나 주변과 비슷해 대상과 배경을 혼동할 수 있다.
# (5) 수집 분야 차이: 센서·촬영 환경·대상 종류가 달라지면 한 환경에서 맞춘 방법이 덜 맞을 수 있다.
# (6) 의미 해석: 컴퓨터는 숫자 배열에서 이름·관계·문맥을 알아내야 한다.
#
# 제한된 환경에서 높은 성능을 얻었다고 다양한 실제 환경에서도 같은 성능을 보장하지는 못한다.
# PPT의 AGI(Artificial General Intelligence)는 더 넓은 범위의 지능을 이야기하는 맥락이다.
# 특정 물체를 잘 검출하는 능력과 범용 지능은 구별한다.
#
# [손 그림자 과제에 연결: ch4_손워터셰드.py]
# 피부색 범위를 좁히면 그림자는 줄어도 밝은 손바닥이나 어두운 손 부분까지 빠질 수 있다.
# 같은 손의 색이 조명에 따라 바뀌고 배경 그림자의 색과 겹칠 수 있기 때문이다.
# 가우시안·메디안은 잡음 완화에 쓰이며, 손과 그림자의 의미를 이해해 그림자만 골라 없애지는 않는다.
# 워터셰드도 잘못 확정한 전경·배경 마커를 모두 고쳐 주지 않는다.
# 이 사례는 환경 변화와 수동 규칙의 일반화 한계를 보여 준다.


#%% 4. 비전이 푸는 여섯 기본 문제 [PPT 17쪽]
# ① 분류(classification)
# 질문: 무엇인가?  전형적인 출력: 클래스 이름과 점수.
# 예: 영상의 주된 대상이 고양이인지 개인지 판단한다. 위치를 반드시 출력하는 것은 아니다.
#
# ② 검출(detection)
# 질문: 무엇이 어디에 있는가?  전형적인 출력: 대상별 클래스와 위치.
# 예: 사람 2명과 자동차 1대의 위치를 상자 등으로 나타낸다.
# 상자는 물체 주변 배경도 포함할 수 있으므로 정확한 픽셀 영역과는 다르다.
#
# ③ 분할(segmentation)
# 질문: 어느 픽셀이 어느 영역에 속하는가?  출력: 픽셀별 영역 번호나 마스크.
# 예: 손 픽셀과 배경 픽셀을 구분한다. 워터셰드·GrabCut·색 마스크가 관련된다.
# 보충: 의미 분할은 픽셀의 클래스를, 개체 분할은 같은 클래스 안의 서로 다른 물체도 구분한다.
# 모든 분할이 물체 이름을 알아내는 것은 아니다. 단순 전경/배경 분할도 있다.
#
# ④ 추적(tracking)
# 질문: 시간이 지나도 같은 대상인가, 어디로 이동했는가?  출력: ID·위치·궤적 등.
# 예: 이전 프레임의 사람 A를 다음 프레임에서도 A로 연결한다.
# 매 프레임 상자를 다시 찾는 것만으로 같은 대상의 ID가 유지되지는 않는다. 프레임 사이 대응이 필요하다.
#
# ⑤ 행동 분석(action/activity analysis)
# 질문: 무슨 동작이나 활동을 하는가?  출력: 걷기·뛰기·스파이크 등의 행동과 관계.
# 추적은 대상의 시간상 연결, 행동 분석은 동작의 의미를 다룬다. 두 작업을 함께 사용할 수 있다.
#
# ⑥ 이미지 생성(image generation)
# 질문: 조건에 맞춰 어떤 영상을 만들 것인가?  출력: 새 영상이나 수정 영상.
# 예: 텍스트로 설명한 장면을 생성한다. 주어진 장면을 해석하는 인식과 출력 목표가 다르다.
#
# [기존 코드에서 구분]
# ch4_4_동영상차선.py는 현재 프레임의 차선을 반복 검출하며 물체 ID를 유지하는 추적기는 아니다.
# ch5_1_해리스직접.py는 관심점 검출과 NMS를 한다. 기술자·매칭·추적 전체를 구현한 코드는 아니다.
# '검출'이라는 말은 물체 검출·에지 검출·특징점 검출에서 쓰이므로 무엇을 찾는지와 출력 형식을 함께 본다.


#%% 5. 왜 컴퓨터비전인가? 응용 분야 [PPT 4~8쪽]
# 영상에는 공간 구조와 상태 변화가 풍부하게 담기고 영상·동영상 자료도 널리 사용된다.
# 비전은 사람이 반복하는 시각 작업의 자동화, 수치 측정, 실시간 인지와 행동 판단 등에 쓰인다.
# 생물의 시각을 기계로 구현하려는 연구는 인간 시각을 이해하는 데도 연결된다.
#
# 교통: 차선·차량·보행자 인지, 지능형 교통관리, 자율 주행.
# 산업·물류: 제품·회로기판의 불량 검사, 조립 위치 확인, 물건 분류·집기.
# 보안: 생체인식, 출입 인증, 감시 대상 검출·추적.
# 의료·과학: 의료 영상의 구조·이상 후보 분석, 수술 로봇, 현미경 영상의 정량 분석.
# 농업: 작물·농작업 장면 분석. 군사: 정찰·탐색·로봇의 시각 인지.
# 사진·오락: 사진 변형, 영상 합성, 자동 파노라마, 게임, AR/VR, 교육.
# 모바일·접근성: 장면·문서·문자를 읽고 필요한 정보를 설명하는 응용.
# 3D 복원: 여러 영상의 대응점과 기하 관계로 장면 구조를 추정한다.
#
# 응용마다 중요한 조건이 다르다. 실시간 로봇은 처리 지연, 제품 검사는 작은 차이의 분별을 중시할 수 있다.
# 한 응용에서 좋은 방법이 모든 응용에서 최선인 것은 아니다.
#
# Physical AI: 인지 결과를 로봇·차량·드론 등 실제 세계에서의 행동과 연결하는 맥락이다.
# XAI(Explainable AI): 결과의 근거나 판단 과정을 사람이 이해할 수 있도록 설명하려는 접근이다.
# 결과의 정확도와 설명 가능성은 같은 개념이 아니다.


#%% 6. 생성 비전과 멀티모달 비전 [PPT 3,9쪽]
# 인식/이해: 주어진 영상이 무엇을 보여 주는지 해석한다.
# 생성: 텍스트나 영상 등의 조건에 맞춰 새 시각 정보를 만들거나 기존 영상을 수정한다.
# 멀티모달(multimodal): 영상·텍스트·음성·동작 등 서로 다른 형태의 정보를 함께 다룬다.
# 예: 영상과 질문을 받아 내용을 설명하거나, 텍스트와 참고 영상을 받아 새 영상을 만들 수 있다.
# 따라서 멀티모달은 생성만을 뜻하지 않으며 이해에도 쓰인다.
#
# GAN(Generative Adversarial Network)은 생성기와 판별기를 경쟁적으로 학습시키는 생성 모델의 한 계열이다.
# 생성기는 자료와 비슷한 결과를 만들고, 판별기는 실제 자료와 생성 결과를 구별하도록 학습한다.
# 생성 비전 전체가 GAN만으로 이루어지는 것은 아니다. 이 장은 구체적 학습식보다 개념과 사례를 소개한다.
# 생성 모델은 많은 자료와 계산 자원이 필요할 수 있고 학습도 어려울 수 있다.
#
# PPT에 나온 Firefly·Midjourney·DALL-E·Sora·Veo·Runway·Pika·Kling 등은 생성 서비스의 사례이다.
# 서비스 이름·버전의 나열과 생성 비전의 원리는 구별해서 공부한다.


#%% 7. 문제 해결 도구: 자료 구조·알고리즘·수학·학습 [PPT 11쪽]
# 자료 구조: 처리하는 데이터를 어떤 형태로 저장하고 관계를 표현할지 정한다.
# 예: 영상은 배열, 영역의 이웃 관계는 그래프, 후보 관리는 트리·힙 등의 구조로 표현할 수 있다.
# 알고리즘: 그 자료에 어떤 탐색·갱신·선택 절차를 적용할지 정한다. 정확한 결과와 고속 처리가 중요하다.
#
# 탐욕 방법(greedy): 단계마다 현재 기준에서 유리한 선택을 한다. 항상 전역 최적해를 보장하지는 않는다.
# 동적 프로그래밍(dynamic programming): 부분 문제의 답을 저장·결합해 더 큰 문제를 푼다.
# 한정 분기(branch and bound): 후보를 분기하며 경계 값으로 불필요한 탐색을 줄인다.
# 이 장에서는 문제 해결 도구의 종류로 소개하므로 모든 예제가 이 세 방법을 쓴다고 해석하지 않는다.
