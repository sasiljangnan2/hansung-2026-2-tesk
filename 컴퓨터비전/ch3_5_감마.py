# PPT의 배경 이론과 현재 코드의 구현 범위를 구분하여 공부한다.
#
# 1. 새 픽셀 값을 어디에서 얻는가?
# 점 연산: 같은 위치의 원래 값에서 결정한다. 밝기 이동·반전·감마가 예이다.
# 영역 연산: 주변 이웃 값에서 결정한다. 평균·가우시안·미분이 예이다.
# 기하 연산: 변환한 좌표에서 원본 값을 가져온다. 이동·회전·확대와 보간이 예이다.
# 감마와 가우시안의 이름이 비슷해도 감마는 밝기 거듭제곱, 가우시안은 이웃 가중 평균이다.
#
# 2. 대표적인 점 연산
# 밝기 이동 g=clip(f+c,0,L-1). 더 밝아져도 최댓값을 넘지 않도록 범위를 제한한다.
# 반전 g=L-1-f. 8비트라면 255-f로 검정과 흰색의 관계를 뒤집는다.
# 감마 g=(L-1)*(f/(L-1))**gamma. 0~1로 정규화한 뒤 비선형 거듭제곱을 한다.
# 이 정의에서 0<gamma<1은 중간 밝기를 높이고 gamma>1은 낮춘다. gamma=1은 항등 변환이다.
# 입력 0과 255는 유지되지만 중간 밝기의 간격은 비선형으로 바뀐다.
# 다른 프로그램이 1/gamma를 쓰면 설명 방향이 달라지므로 이름보다 실제 수식을 먼저 본다.
#
# 3. 효과와 한계
# 밝기를 보기 좋게 바꾸는 것과 물체/그림자를 분리하는 것은 다르다. gamma는 소속 레이블을 정하지 않는다.
# 어두운 부분을 올리면 잡음도 더 잘 보일 수 있고 이미 포화·양자화로 잃은 정보를 복원하지는 못한다.
# uint8 단순 덧셈/형변환의 범위 밖 순환과 clip의 포화 처리를 구분한다.
# 아래는 동일 영상을 다섯 gamma로 바꿔 가로로 비교하는 코드이다.
# ==================================================================


import cv2 as cv
import numpy as np
import sys

#%%
# [함수 사용: 입출력·창]
# img=cv.imread(path, flags=cv.IMREAD_COLOR): 파일→배열. 기본 BGR, 읽기 실패 시 None인지 확인한다.
# cv.imshow(winname,img): 이름이 winname인 창에 배열을 표시한다. 저장 함수는 아니다.
# key=cv.waitKey(delay=0): GUI 이벤트·키 처리. 0은 계속 대기, 양수는 ms, 입력 없으면 보통 -1이다.
# cv.destroyAllWindows(): OpenCV 창을 닫는다. 캡처 자원 해제는 cap.release()이다.
img = cv.imread("soccer.jpg")

if img is None:
    sys.exit("No File exists.")

# [함수 사용] dst=cv.resize(src, dsize, fx=0, fy=0, interpolation=cv.INTER_LINEAR)
# dsize=(너비,높이). (0,0)이면 fx·fy 배율로 크기를 정하며, interpolation은 보간법이다. 결과 영상을 반환한다.
img=cv.resize(img, dsize=(0,0), fx=0.25, fy=0.25)

# [서술형] 감마 점 연산
# 관련 PPT: 영상처리_2 11~14쪽
# 특징: 정규화 밝기에 거듭제곱을 적용하는 비선형 밝기 변환이다.
# 장점: 주변 픽셀 계산 없이 중간 밝기를 조절하고, 0과 최댓값은 유지할 수 있다.
# 단점: 영상에 맞는 감마를 정해야 하며 이미 사라진 밝기 정보나 그림자의 소속을 복원하지 못한다.
# 활용: 어둡거나 밝은 영상의 표시 보정, 밝기 변화가 후속 처리에 주는 영향 비교.
# 한 문장 답안: 감마 변환은 중간 밝기를 비선형으로 조절하지만 잡음 제거와 물체 분할을 대신하지 않는다.
# [계산·코드 연결]
# 이 코드: g=255*(f/255)**gamma. gamma<1은 밝게, >1은 어둡게, =1은 그대로.
# f=64일 때 gamma=0.5 -> uint8 127, gamma=1 -> 64, gamma=2 -> 16.
# 이웃을 평균하지 않는 점 연산이다. 1/gamma를 사용하는 다른 정의와 방향을 혼동하지 않는다.
def gamma(f, gamma=1.0):
    f1=f/255.0
    # [함수 사용] dst=np.uint8(values)
    # 값을 8비트 부호 없는 정수로 변환한다. 안전한 범위 표시에는 먼저 clip을 고려하며 좌표값을 8비트로 제한하지 않도록 주의한다.
    return np.uint8(255*(f1**gamma))

# [배열 크기 예측] 현재 축소 후 img.shape=(237,358,3)이다.
# hstack은 너비 축으로 5장을 붙인다. gc.shape=(237,1790,3), dtype=uint8이다.
# 왼쪽부터 gamma 0.5,0.75,1,2,3 순서이므로 처음이 밝고 뒤로 갈수록 어둡다.
# [함수 사용] dst=np.hstack((a,b))
# 영상은 너비 축으로 연결하므로 높이·채널 등 다른 축이 같아야 한다. 새 연결 배열을 반환한다.
gc = np.hstack((gamma(img, 0.5),gamma(img, 0.75), gamma(img, 1.0), 
                gamma(img, 2.0), gamma(img, 3.0)))    
cv.imshow("gamma", gc)

cv.waitKey()
cv.destroyAllWindows()