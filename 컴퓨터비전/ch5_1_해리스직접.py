# 장점: 2차 곡률 정보를 사용해 1차 미분 곱과 다른 형태의 국소 구조를 평가할 수 있다.
# 단점: 2차 미분은 잡음에 민감하며 평활화·스케일과 응답 기준을 함께 정해야 한다.
# 활용: 가우시안 평활화와 결합한 2차 미분 기반 지역 특징의 발상.
# 한 문장 답안: Hessian은 밝기의 2차 변화로 국소 구조를 보지만 잡음과 스케일 선택에 민감하다.
# [계산·코드 연결]
# H=[[Ixx,Ixy],[Ixy,Iyy]], det(H)=Ixx*Iyy-Ixy**2.
# 이 파일의 dxx=dx*dx는 2차 미분이 아니다. Harris 구조 행렬과 Hessian은 다른 행렬이다.
