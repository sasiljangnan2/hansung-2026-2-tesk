# [선행 이론] 지역 특징의 조건부터 Harris 대표점까지 — 먼저 읽는 이론
# 근거: 5장 지역특징_1 2~34쪽
# 읽는 순서: 선행 이론 → 관련 코드 앞의 서술형 요약 → 계산·출력 주석.
# PPT의 배경 이론과 현재 코드의 구현 범위를 구분하여 공부한다.
#
# 1. 대응점과 지역 특징의 발상 [PPT 2~6쪽]
# 대응점 문제는 다른 시점/프레임에서도 같은 장면의 같은 지점에 해당하는 점 쌍을 찾는 문제이다.
# 추적·파노라마·스테레오·카메라 보정 등에 쓰이며, 모든 픽셀보다 비교에 좋은 지점을 고르는 것이 유리하다.
# 좋은 지점이 물체의 실제 기하학적 모퉁이에만 있어야 하는 것은 아니다. 다시 검출되는 반복성을 중요하게 본다.
# 일반적인 지역 특징은 <위치,스케일,방향,특징 기술자>로 표현한다.
# 검출(detection)은 위치·관찰 범위/스케일을 고르고, 기술(description)은 주변 패턴을 비교용 벡터로 나타낸다.
# 매칭(matching)은 서로 다른 영상의 기술자를 비교해 대응 후보를 찾는 단계이다.
# '검출→기술→매칭'은 세 단계이다. Harris 응답 계산만 했다고 기술자·매칭까지 완료된 것은 아니다.
#
# 2. 지역 특징이 만족해야 할 여섯 조건 [PPT 7쪽: 첨부 화면]
# (1) 반복성(repeatability): 조명·시점·프레임이 달라져도 같은 실제 지점이 두 영상에서 다시 검출되어야 한다.
#     한 영상에서 코너 응답이 매우 커도 다른 영상에서 사라지면 대응점으로 쓰기 어렵다.
# (2) 분별력(distinctiveness): 다른 지점과 구별될 만큼 주변 패턴/기술자가 달라야 한다.
#     반복되는 창문·타일은 점이 많아도 서로 비슷해 어느 지점끼리 대응하는지 모호할 수 있다.
# (3) 지역성(locality): 좁은 주변 정보로 특징을 결정하여 일부 가림·배경 변화가 나머지 특징까지 망치지 않게 한다.
#     물체 전체가 조금 가려져도 보이는 부분의 지역 특징은 남을 수 있다는 장점이 있다.
# (4) 정확성(accuracy): 검출 위치·스케일·방향 등이 실제 대응 위치를 정밀하고 안정적으로 가리켜야 한다.
#     반복성은 '다시 찾는가', 정확성은 '찾은 위치가 얼마나 정밀한가'로 구분한다.
# (5) 적당한 양: 물체를 설명하고 대응을 추정할 만큼 충분하되 불필요한 점만 과도하게 늘리지 않아야 한다.
#     너무 적으면 비교 근거가 부족하고 너무 많으면 계산·중복·잘못된 대응 후보가 늘 수 있다.
# (6) 계산 효율: 검출·기술·매칭을 응용이 허용하는 시간과 메모리 안에서 처리해야 한다.
#     영상 한 장의 실행 시간뿐 아니라 반복되는 전체 파이프라인 비용도 고려한다.
#
# 3. 조건들의 길항 관계(trade-off) [PPT 7쪽]
# 모든 조건을 무조건 동시에 최대화할 수 있는 것이 아니라 응용 목적에 따라 균형점을 고른다.
# 실시간 작업: 처리 지연이 중요하므로 일부 반복성/정교함을 희생하더라도 빠른 방법·적은 점을 선택할 수 있다.
# 지역성과 분별력: 더 넓은 문맥을 보면 구별 정보는 늘 수 있지만 좁은 영역만 보는 지역성은 낮아질 수 있다.
# 반대로 창을 너무 작게 하면 가림의 영향은 줄어도 비슷한 지역을 구분할 정보가 부족할 수 있다.
# 오프라인 작업: 즉시 결과가 필요하지 않다면 시간을 더 써 정확한 검출·기술·비교를 선택할 수 있다.
# 특징 개수와 효율: 점이 늘면 정보도 늘 수 있지만 검출 후 기술·매칭 비용도 함께 커진다.
# 강의의 길항 관계는 선택의 발상이다. 분별력을 올리면 언제나 정확히 같은 양만큼 지역성이 떨어진다는 수식은 아니다.
#
# 4. 평탄한 곳·에지·코너가 다른 이유 [PPT 8~13쪽]
# 평탄한 창은 어느 방향으로 조금 옮겨도 밝기가 비슷해 위치를 구별하기 어렵다.
# 에지 창은 경계를 가로지르면 밝기가 크게 변하지만 접선을 따라 옮기면 비슷하여 한 방향 위치가 모호하다.
# 코너/관심점은 여러 방향으로 옮겨도 패턴이 달라지는 곳이라 대응 위치를 정하기 유리하다.
# Moravec은 창 이동의 제곱차 합을 방향별로 구하고 그중 최소값도 큰 점을 찾는다.
# 제한된 네 방향·한 픽셀 이동만 보며 잡음 대처가 약하다는 한계를 Harris의 가중 집계와 비교한다.
#
# 5. Harris의 행렬과 응답 [PPT 14~24쪽]
# 이웃의 이동 전후 가중 제곱차를 Taylor 근사하면 작은 이동 벡터와 구조 행렬 A의 이차형식으로 볼 수 있다.
# A는 [[sum(w*Ix**2),sum(w*Ix*Iy)],[sum(w*Ix*Iy),sum(w*Iy**2)]]이다.
# 직접 구현(ch5_1)은 미분 곱에 가우시안 필터를 적용해 이 합을 구한다. 원영상 흐림과 가중 집계의 대상을 구분한다.
# 고유값 둘 다 작음=평탄, 하나만 큼=에지, 둘 다 큼=두 방향 변화가 큰 후보이다.
# C=det(A)-k*trace(A)**2로 고유값을 직접 계산하지 않고 후보 가능성을 평가한다.
# 임계값만 넘긴 점은 한 코너 주변에 여러 개 모일 수 있어 NMS로 대표점을 고른다.
# 큰 응답·표시 밝기·선택된 좌표는 서로 다른 결과이다. dtype 변환/반올림 표시도 계산 자체와 구분한다.
#
# 6. 불변성의 범위와 구현 범위 [PPT 25~26,34쪽]
# 이동/회전 후에도 같은 실제 지점의 관심점이 검출되는 성질을 논하지만 좌표 숫자가 그대로라는 뜻은 아니다.
# 고정 이웃 크기의 Harris는 스케일 불변이 아니다. 확대되면 같은 창 안에 보이는 구조가 달라진다.
# 실제 픽셀 영상은 회전 보간·양자화·잡음 때문에 이상적인 응답이 정확히 일치하지 않을 수 있다.
# 이 제공 PPT에서 SIFT·매칭·호모그래피는 차례에만 나오는 부분이므로 본문 구현으로 확장하지 않았다.
#
# 7. 아래 직접 구현에서 확인할 것
# 10×10 삼각형→미분→미분 곱→가우시안 집계→C→3×3 NMS 순서이다.
# dxx=dx*dx는 1차 미분의 제곱이며 Hessian의 실제 2차 미분 Ixx와 다르다.
# 출력의 선택점 세 곳과 응답값은 아래 print 주석에 두었다. 이 파일은 기술자·매칭을 계산하지 않는다.
