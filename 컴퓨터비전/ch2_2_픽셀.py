# [선행 이론] 디지털 영상의 획득·표현을 먼저 이해하기
# 근거: 3장 영상처리_1 3~10,14~16,20쪽
# 읽는 순서: 선행 이론 → 관련 코드 앞의 서술형 요약 → 계산·출력 주석.
# PPT의 배경 이론과 현재 코드의 구현 범위를 구분하여 공부한다.
#
# 1. 영상 처리와 컴퓨터 비전
# 영상 처리는 목적에 맞게 원래 영상을 다른 영상으로 바꾸는 작업이다.
# 보기 좋게 만드는 화질 개선뿐 아니라, 뒤의 검출·인식을 쉽게 만드는 전처리에도 사용한다.
# 배열의 숫자를 읽는 것과 그 숫자가 나타내는 물체의 의미를 이해하는 것은 다른 단계이다.
#
# 2. 빛을 숫자로 바꾸는 두 과정
# CCD/CMOS 센서는 빛을 전기적 신호로 바꾸고 ADC가 이를 디지털 신호로 변환한다.
# 표본화(sampling): 공간을 M×N개의 격자로 나누어 어느 위치를 픽셀로 기록할지 정한다.
# 양자화(quantization): 각 픽셀의 밝기를 L개의 이산 단계 중 하나로 기록한다.
# 해상도를 높이는 것과 밝기 단계 수를 늘리는 것은 서로 다른 변화이다.
# 채널당 b비트이면 L=2**b. uint8은 8비트라 0~255의 256단계이다.
#
# 3. 영상의 축과 채널
# 명암 영상은 (높이,너비)의 2차원, 컬러는 (높이,너비,채널)의 3차원 배열이다.
# 동영상은 여러 프레임을 시간 순서로 본다. 채널 수와 배열 차원 수를 혼동하지 않는다.
# 깊이 영상의 depth는 거리 정보이고, CV_32F의 비트 깊이와는 다른 뜻이다.
# OpenCV의 기본 컬러 순서는 B,G,R이다. img[y,x,2]는 그 위치의 빨간 성분이다.
# 배열 인덱스 [행,열]=[y,x]와 그리기 함수의 좌표 (x,y)는 순서가 반대이다.
# shape는 축별 크기, ndim은 축 수, dtype은 원소 자료형, type은 객체 종류이다.
#
# 4. 영상 읽기와 잘라내기
# 기본 imread는 BGR 3채널, GRAYSCALE은 명암, UNCHANGED는 알파 등 원래 채널을 보존한다.
# 알파는 투명도이다. 4채널 자료를 읽는다고 일반 명암 영상도 4차원이 되는 것은 아니다.
# 슬라이싱 y1:y2,x1:x2는 끝 y2,x2를 포함하지 않는다. 패치 크기는 (y2-y1,x2-x1)이다.
# NumPy 기본 슬라이스는 원본과 메모리를 공유할 수 있다. 독립 수정에는 copy()를 고려한다.
# 아래 코드는 이 이론 중 배열 종류·크기·BGR 값·패치 표시를 직접 확인한다.
# ==================================================================


# [1장 연결 이론] 컴퓨터비전의 정의·역문제 [1장 소개 PPT 2~3,10,17쪽]
# 컴퓨터비전은 영상에서 물체·장면의 의미 있는 설명을 구하는 분야이다.
# 전형적인 방향은 영상처리=영상→영상, 비전=영상→정보·설명, 그래픽스=장면 설명→영상이다.
# 비전은 2D 관측으로 3D 세계의 원인을 추정하는 역문제이다. 투영 과정에서 정보가 줄어든다.
# 작고 가까운 물체와 크고 먼 물체가 비슷하게 찍히는 등 같은 관측에 여러 해석이 가능하다.
# 조명·시점·변형·가림이 배열 값을 바꾸므로 숫자를 읽는 것과 의미를 이해하는 것은 다르다.
# 아래 type/shape/픽셀 출력은 영상의 표현을 확인하며 물체의 이름이나 위치를 인식하지는 않는다.
# 기본 과업: 분류=무엇, 검출=무엇/어디, 분할=픽셀별 영역, 추적=시간에 따른 동일 대상 연결.
# 자세한 비교·그림·예상 답안은 시험공부/1장_소개_시험정리.docx에 정리했다.


#%% [PPT 전체 확인 보충] 배열 함수·영상 읽기 옵션
# 관련 PPT: 영상처리_1 6·8~11·15·20쪽. 아래 호출은 사용법을 읽는 주석 예시이다.
# [함수 사용] np.empty(shape,dtype=np.uint8): 초기화하지 않은 배열. 값은 미정이며 0이나 난수가 보장되지 않는다.
# [함수 사용] np.full(shape,fill_value,dtype=None): 지정한 값으로 전부 채운 새 배열.
# 예: white=np.full((2,3),255,np.uint8) -> [[255,255,255],[255,255,255]], shape=(2,3), dtype=uint8.
# 예: yellow=np.full((240,320,3),(0,255,255),np.uint8) -> BGR의 노란 영상.
# np.zeros/np.ones/np.empty는 dtype을 생략하면 보통 float64이다. 영상의 0~255 배열은 dtype=np.uint8을 명시한다.
# PPT의 np.unit8은 오타이며 실제 이름은 np.uint8이다. float64 0~255와 uint8 0~255는 imshow 표시 규칙도 다르다.
#
# [함수 사용] np.argmin(a,axis=None)/np.argmax(a,axis=None): 값이 아닌 최소/최대의 인덱스. 축 생략은 펼친 순서이고 동률은 첫 위치이다.
# 예: a=np.array([[9,2,7],[1,8,3]]) -> np.min(a)=1, np.argmin(a)=3, np.argmax(a)=0.
# [함수 사용] a.reshape(newshape): 원소 수를 유지하고 모양만 변경. -1은 나머지 크기를 추정하며 가능하면 메모리를 공유한다.
# 예: a.reshape(3,2) -> [[9,2],[7,1],[8,3]]. reshape는 전치와 다르다.
# [함수 사용] a.transpose(axes=None) 또는 a.T: 축 순서 변경(기본 역순). 보통 메모리를 공유하므로 독립 수정에는 copy()를 사용한다.
# 예: a.T -> [[9,1],[2,8],[7,3]], shape=(3,2). 3D 영상의 .T는 (H,W,C)→(C,W,H)이므로 단순 가로세로 회전이 아니다.
#
# [PPT 옵션: cv.imread] IMREAD_COLOR=1은 BGR, GRAYSCALE=0은 명암, UNCHANGED=-1은 알파와 깊이 등을 보존한다.
# ANYDEPTH는 파일이 지원하는 16/32비트 깊이를 보존, ANYCOLOR는 가능한 색 형식으로 읽는 옵션이다.
# REDUCED_COLOR_2/4/8과 REDUCED_GRAYSCALE_2/4/8은 각 축을 1/2·1/4·1/8로 축소해 읽는다(형식별 지원 차이).
# IGNORE_ORIENTATION은 EXIF 회전 적용을 무시, LOAD_GDAL은 GDAL 지원 빌드에서 해당 로더를 사용한다.
#
# [색 표현 연결] RGB는 세 축의 색 강도, BGR은 그 채널을 배열에 저장하는 순서이다.
# 원추세포 S/M/L은 짧은/중간/긴 파장에 대한 감도가 겹치며 디지털 B/G/R 채널과 완전히 같은 센서는 아니다.
# Lab는 색 거리와 지각 차이를 더 가깝게 표현하려는 공간이다. RGB의 같은 수치 거리가 같은 지각 차이를 보장하지 않는다.

import cv2 as cv
from cv_assets import read_image
import sys

#%%
# 영상의 배열 표현 [영상처리_1 PPT 5~10쪽]
# 배열은 [행, 열, 채널]=[y,x,BGR] 순서이다. shape는 높이·너비·채널 수를 뜻한다.
# 그리기 함수에 넣는 좌표 (x,y)와 배열 인덱스 [y,x]를 구분한다.
# [함수 사용: 입출력·창]
# img=cv.imread(path, flags=cv.IMREAD_COLOR): 파일→배열. 기본 BGR, 읽기 실패 시 None인지 확인한다.
# cv.imshow(winname,img): 이름이 winname인 창에 배열을 표시한다. 저장 함수는 아니다.
# key=cv.waitKey(delay=0): GUI 이벤트·키 처리. 0은 계속 대기, 양수는 ms, 입력 없으면 보통 -1이다.
# cv.destroyAllWindows(): OpenCV 창을 닫는다. 캡처 자원 해제는 cap.release()이다.
img=read_image('soccer.jpg')

if img is None:
    sys.exit("No File exists.")

# [서술형] 영상의 배열 표현과 채널 분석
# 관련 PPT: 영상처리_1 5~10,14~16쪽
# 특징: 영상을 높이×너비×채널의 NumPy 배열로 보고 값·모양·채널을 나누어 읽는다.
# 장점: 픽셀 접근·잘라내기·벡터 연산을 같은 배열 표현으로 처리할 수 있다.
# 단점: 배열 자체에는 물체의 의미가 없고, 축 순서와 자료형을 혼동하면 잘못 해석한다.
# 활용: 색 채널 분리, 관심 영역 추출, 뒤 단계의 입력 크기·자료형 확인.
# 한 문장 답안: 영상은 픽셀 배열로 표현하며 shape는 크기, dtype은 값의 자료형, 채널은 색 성분을 뜻한다.
# [계산·코드 연결]
# 현재 shape=(948,1434,3), type은 ndarray, 한 채널 원소의 type은 numpy.uint8이다.
# 배열은 [y,x,c], 그리기 함수 좌표는 (x,y)이다. uint8은 0~255의 256단계이다.
# type(img) 단독 표현식은 .py에서 출력되지 않는다. 아래 print 결과는 그대로 확인한다.
print(type(img))  # 출력: <class 'numpy.ndarray'>
print(img.shape)  # 출력: (948, 1434, 3)
type(img)
#pixel elements
print(img[0,0,0], img[0,0,1], img[0,0,2])  # 출력: 162 104 98 (B G R)
print(img[0,1,0], img[0,1,1], img[0,1,2])  # 출력: 163 105 99 (현재 soccer.jpg)
# [출력 해석] B/G/R 각각 10x10 배열 세 장을 순서대로 출력한다. 한 10x10x3 배열 출력과 다르다.
# B 첫 행: [162 163 162 160 164 161 163 166 169 168]
# G 첫 행: [104 105 103 101 102 100 98 103 101 101]
# R 첫 행: [98 99 94 91 92 86 83 83 82 80]  (영상 파일이 같을 때의 값)
# 영상처리_1 PPT 5~10쪽: 표본화는 공간 해상도, 양자화는 밝기 단계 수를 정한다.
# 채널당 8비트이면 2**8=256단계이며, 컬러의 3채널은 픽셀당 3바이트이다.
# 슬라이싱 0:10은 0~9를 포함한다. 값이 바뀌어도 높이·너비는 각각 10이라는 규칙은 같다.
print(img[0:10,0:10,0], img[0:10,0:10,1], img[0:10,0:10,2])   

cv.imshow('Img Display', img)
cv.imshow("Partial", img[0:10,0:10,:])

cv.waitKey()
cv.destroyAllWindows()
